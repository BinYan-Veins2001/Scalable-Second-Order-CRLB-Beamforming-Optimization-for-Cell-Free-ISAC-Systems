function [signature,manifest]=paperfig_efficiency_signature()
%PAPERFIG_EFFICIENCY_SIGNATURE Numerical and physical inputs of Fig. 6.
% Graphics/export sources are deliberately excluded from the timing cache.
s=paperfig_setup();
relative={ ...
    'sim_twc/common/simtwc_make_problem.m', ...
    'sim_twc/common/simtwc_config.m', ...
    'sim_twc/common/simtwc_setup.m', ...
    'paper_figures/common/paperfig_signature.m', ...
    'paper_figures/common/paperfig_efficiency_signature.m', ...
    'paper_figures/common/paperfig_efficiency_dense_hessian.m', ...
    'paper_figures/common/paperfig_efficiency_dense_evd.m', ...
    'paper_figures/compute/paperfig_compute_efficiency.m', ...
    'main_fig06_structured_curvature_efficiency.m', ...
    'tests/test_paperfig_efficiency.m'};
digest=java.security.MessageDigest.getInstance('SHA-256');
digest.update(unicode2native(paperfig_signature(),'UTF-8'));
manifest=struct('file',relative,'sha256',cell(size(relative)));
for j=1:numel(relative)
    content=fileread(fullfile(s.root,relative{j}));
    bytes=unicode2native(content,'UTF-8');
    one=java.security.MessageDigest.getInstance('SHA-256'); one.update(bytes);
    manifest(j).sha256=hex(one.digest());
    digest.update(unicode2native(relative{j},'UTF-8')); digest.update(bytes);
end
signature=hex(digest.digest());
end

function value=hex(bytes)
value=lower(reshape(dec2hex(typecast(bytes,'uint8'),2).',1,[]));
end
