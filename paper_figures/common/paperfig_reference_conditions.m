function paperfig_reference_conditions(d,folder)
%PAPERFIG_REFERENCE_CONDITIONS Separate empirical contraction from hypotheses.
rows=cell(numel(d.trials),15);
for j=1:numel(d.trials)
    t=d.trials{j}; a=t.reference_check;
    rows(j,:)={t.seed,a.licq,a.positive_multipliers,a.horizontal_positive_definite, ...
        a.all_local_assumptions,a.minimum_active_multiplier,a.horizontal_lambda_min, ...
        a.tangent_residual,a.face_residual,max(t.face_ratio),max(t.forcing_ratio), ...
        max(t.normal_ratio),nnz(t.fit_mask),nnz(t.r1>=t.r0),a.full_nnls_kkt};
end
writetable(cell2table(rows,'VariableNames',{'seed','LICQ','strict_positive_multipliers', ...
    'horizontal_positive_definite','all_local_assumptions','min_active_multiplier', ...
    'horizontal_lambda_min','reference_tangent_residual','reference_face_residual', ...
    'max_face_ratio','max_linear_forcing_ratio','max_normal_ratio', ...
    'qualified_samples','noncontracting_samples','full_NNLS_KKT'}),fullfile(folder,'reference_conditions.csv'));
end
