function fig = simtwc_plot_fig16()
%SIMTWC_PLOT_FIG16 CRLB, tangent gradient and signed horizontal curvature.

simtwc_setup(); d=simtwc_load_data(16); st=simtwc_ieee_style('single');
if ~isfield(d,'lambda_min_horizontal') || ...
        numel(d.lambda_min_horizontal)~=numel(d.iter)
    error('Fig. 16 curvature history is absent; run its compute program.');
end
fig=figure('Units','inches','Position',[1 1 st.width_in 3.05]);
marks=unique(round(linspace(1,numel(d.iter),min(9,numel(d.iter)))));

ax=axes(fig); hold(ax,'on'); box(ax,'on'); grid(ax,'on');

yyaxis(ax,'left');
h1=plot(ax,d.iter,max(d.crlb,realmin),'-d','Color',[0.80 0.12 0.20], ...
    'MarkerFaceColor','w','MarkerIndices',marks, ...
    'LineWidth',st.line_width,'MarkerSize',st.marker_size);
h2=plot(ax,d.iter,max(d.tangent_grad_norm,realmin),'--o', ...
    'Color',[0.00 0.45 0.70], ...
    'MarkerFaceColor','w','MarkerIndices',marks, ...
    'LineWidth',st.line_width,'MarkerSize',st.marker_size);
ax.YAxis(1).Scale='log';
ax.YAxis(1).Color=[0.18 0.18 0.18];
ylabel(ax,'CRLB ($\mathrm{m}^2$), $\|\mathbf g_k^{\mathrm{tan}}\|_2$ (log)', ...
    'Interpreter','latex');

yyaxis(ax,'right');
transition=1e-4;
curve=simtwc_curvature_axis(d.lambda_min_horizontal,transition);
h3=plot(ax,d.iter,curve,'-.s','Color',[0.42 0.28 0.68], ...
    'MarkerFaceColor','w','MarkerIndices',marks, ...
    'LineWidth',st.line_width,'MarkerSize',st.marker_size);
yline(ax,0,':','Color',[0.48 0.48 0.48], ...
    'LineWidth',st.reference_line_width);
finite_curve=curve(isfinite(curve));
if isempty(finite_curve); error('Fig. 16 has no finite curvature values.'); end
span=max(0.45,max(finite_curve)-min(finite_curve));
ylim(ax,[min(0,min(finite_curve))-0.10*span, ...
    max(0,max(finite_curve))+0.10*span]);
simtwc_curvature_axis([],transition,ax);
ax.YAxis(2).Color=[0.42 0.28 0.68];
xlabel(ax,'Iteration Index','Interpreter','latex');
ylabel(ax,'$\hat\lambda_{\min,k}^{\mathrm H}$ (signed log)', ...
    'Interpreter','latex');
legend(ax,[h1 h2 h3], ...
    {'CRLB','$\|\mathbf g_k^{\mathrm{tan}}\|_2$', ...
    '$\hat\lambda_{\min,k}^{\mathrm H}$'}, ...
    'Interpreter','latex','Location','northoutside', ...
    'Orientation','horizontal','Box','off', ...
    'FontSize',st.legend_font_size);
simtwc_export_figure(fig,'fig16_costar_convergence');
end
