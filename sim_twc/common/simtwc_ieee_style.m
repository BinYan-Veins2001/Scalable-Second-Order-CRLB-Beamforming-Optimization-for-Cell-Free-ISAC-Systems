function st = simtwc_ieee_style(width_mode)
%SIMTWC_IEEE_STYLE Consistent IEEE TWC figure typography and dimensions.

if nargin<1; width_mode='double'; end
if strcmpi(width_mode,'single'); width=3.5; else; width=7.16; end
st.width_in=width;
st.axis_font_size=8;
st.legend_font_size=7;
st.line_width=1.5;
st.marker_size=5;
% Match Fig. 8: clean method curves; uncertainty stays available on demand.
st.show_curve_se=strcmpi(strtrim(getenv('COSTAR_PLOT_SE')),'1');
st.error_line_width=0.75;
st.error_cap_size=2.5;
st.reference_line_width=1.0;
st.bar_edge_color=[0.25 0.25 0.25];
st.bar_edge_width=0.55;
st.font_name='Times New Roman';
st.grid_color=[0.78 0.78 0.78];
set(groot,'defaultAxesFontName',st.font_name, ...
    'defaultTextFontName',st.font_name, ...
    'defaultLegendFontName',st.font_name, ...
    'defaultAxesFontSize',st.axis_font_size, ...
    'defaultTextFontSize',st.axis_font_size, ...
    'defaultAxesLineWidth',0.7, ...
    'defaultAxesGridColor',st.grid_color, ...
    'defaultAxesGridAlpha',0.38, ...
    'defaultAxesMinorGridAlpha',0.20, ...
    'defaultLineLineWidth',st.line_width, ...
    'defaultLineMarkerSize',st.marker_size, ...
    'defaultAxesTickLabelInterpreter','tex', ...
    'defaultLegendInterpreter','tex', ...
    'defaultTextInterpreter','tex');
end
