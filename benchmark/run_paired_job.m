function result = run_paired_job(job_file)
%RUN_PAIRED_JOB Run one old/new solver in an otherwise fresh MATLAB process.
loaded=load(job_file,'job'); job=loaded.job;
% Windows MATLAB ships a Perl runtime that cannot use the inherited Unix
% C.UTF-8 locale. Clear it only in this dedicated worker process before
% restoredefaultpath invokes toolbox path discovery.
setenv('LC_ALL',''); setenv('LC_CTYPE',''); setenv('LANG','');
restoredefaultpath;
addpath(genpath(job.project_root),'-begin');
addpath(job.benchmark_root,'-begin');
setenv('COSTAR_QUICK',''); setenv('COSTAR_SMOKE','');
assert(startsWith(which('solve_costar'),job.project_root), ...
    'Wrong COSTAR project on the MATLAB path.');
maxNumCompThreads(job.compute_threads);
saved=load(job.problem_file,'p'); p=saved.p;
initial_W=p.initialization.Wmat;
if strcmp(job.label,'new')
    % The physical problem and external W0 remain bitwise identical. Only
    % algorithm defaults are supplied by the chosen implementation.
    current=default_config(); p.cfg.costar=current.costar;
end
p.cfg.opt.verbose=false; p.cfg.costar.phase1_verbose=false;
rng(p.seed,'twister');
sol=struct(); hist=struct(); audit=struct(); paper_audit=struct();
row=struct('case_name',job.case_name,'seed',job.seed,'label',job.label, ...
    'M',p.cfg.sys.M,'U',p.cfg.sys.U,'Nt',p.cfg.sys.Nt, ...
    'dimension',2*p.cfg.sys.M*p.cfg.sys.Nt*p.cfg.sys.U, ...
    'executed',false,'optimization_s',NaN, ...
    'initialization_s',p.initialization.runtime_s,'crlb',NaN, ...
    'initial_crlb',NaN,'kkt',NaN,'primal',NaN,'stationarity',NaN, ...
    'complementarity',NaN,'lambda_min_tangent',NaN, ...
    'lambda_min_ambient',NaN,'first_order_pass',false, ...
    'second_order_pass',false,'joint_pass',false, ...
    'licq',false,'all_multipliers_positive',false, ...
    'critical_cone_epsilon2',NaN,'solver_success',false, ...
    'solver_kkt',NaN,'solver_curvature_bound',NaN, ...
    'solver_critical_cone_tolerance',NaN,'paper_kkt',NaN, ...
    'paper_lambda_min_tangent',NaN,'paper_joint_pass',false, ...
    'paper_primal',NaN,'paper_cone_epsilon2',NaN, ...
    'hvp_calls',0,'tcg_calls',0,'tcg_iterations',0,'nnls_calls',0, ...
    'guard_calls',0,'guard_accepted',0,'structured_checks',0, ...
    'structured_full_passes',0,'structured_tangent_passes',0, ...
    'negative_curvature_steps',0,'accepted_steps',0, ...
    'rejected_steps',0,'restoration_iterations',0, ...
    'threshold_refinements',0,'stage_refinements',0, ...
    'inward_qp_calls',0,'inward_qp_sweeps',0, ...
    'normal_newton_calls',0,'normal_newton_accepted',0, ...
    'audit_s',NaN,'message','','error_id','');
try
    initial_metrics=evaluate_beamforming_solution(p.cfg,p.channels,p.smat, ...
        p.initialization.wcell);
    row.initial_crlb=initial_metrics.crlb;
    timer=tic;
    [sol,hist]=solve_costar(p.cfg,p.channels,p.smat, ...
        p.initialization.wcell,job.solver_options);
    row.optimization_s=toc(timer);
    assert(isequal(initial_W,p.initialization.Wmat), ...
        'The shared initial point was modified.');
    if isfield(sol,'z'); z=sol.z;
    elseif isfield(sol,'Wmat'); z=complex_matrix_to_real_vector(sol.Wmat);
    else; z=complex_matrix_to_real_vector( ...
            vectorize_wcell_to_matrix(p.cfg,sol.wcell)); end
    audit=benchmark_endpoint_audit(p,z,struct('dense_max_dim',job.dense_max_dim));
    row.executed=true; row.crlb=audit.crlb;
    row.kkt=audit.kkt; row.primal=audit.primal;
    row.stationarity=audit.stationarity; row.complementarity=audit.complementarity;
    row.lambda_min_tangent=audit.lambda_min_tangent;
    row.lambda_min_ambient=audit.lambda_min_ambient;
    row.first_order_pass=audit.first_order_pass;
    row.second_order_pass=audit.second_order_pass;
    row.joint_pass=audit.joint_pass; row.licq=audit.licq;
    row.all_multipliers_positive=audit.all_multipliers_positive;
    row.critical_cone_epsilon2=audit.critical_cone_epsilon2;
    row.audit_s=audit.elapsed_s;
    row.solver_success=logical(value_or(sol,'success',false));
    row.solver_kkt=value_or(sol,'kkt_residual',NaN);
    row.solver_curvature_bound=value_or(sol,'curvature_lower_bound',NaN);
    row.solver_critical_cone_tolerance=value_or(sol,'critical_cone_tolerance',NaN);
    row.message=char(string(value_or(sol,'message','completed')));
    if isfield(sol,'work')
        work=sol.work;
        names={'hvp_calls','tcg_calls','tcg_iterations','nnls_calls', ...
            'guard_calls','guard_accepted','structured_checks', ...
            'structured_full_passes','structured_tangent_passes', ...
            'negative_curvature_steps','accepted_steps','rejected_steps', ...
            'restoration_iterations','threshold_refinements','stage_refinements', ...
            'inward_qp_calls','inward_qp_sweeps', ...
            'normal_newton_calls','normal_newton_accepted'};
        for j=1:numel(names); row.(names{j})=value_or(work,names{j},0); end
        row.guard_calls=value_or(work,'safeguard_calls',row.guard_calls);
        row.guard_accepted=value_or(work,'safeguard_accepted',row.guard_accepted);
        row.structured_full_passes=value_or(work,'structured_passes',row.structured_full_passes);
        row.structured_tangent_passes=value_or(work,'tangent_checks',row.structured_tangent_passes);
    end
    % New solver endpoint multipliers are assessed separately from the common
    % fixed-threshold comparison whenever they are exposed by the solver.
    if isfield(sol,'lambda') && numel(sol.lambda)==p.cfg.sys.U+p.cfg.sys.M
        paper_options=struct('dense_max_dim',job.dense_max_dim, ...
            'lambda',sol.lambda);
        if isfield(sol,'active'); paper_options.active=sol.active; end
        paper_audit=benchmark_endpoint_audit(p,z,paper_options);
        row.paper_kkt=paper_audit.kkt;
        row.paper_lambda_min_tangent=paper_audit.lambda_min_tangent;
        row.paper_joint_pass=paper_audit.joint_pass;
        row.paper_primal=paper_audit.primal;
        row.paper_cone_epsilon2=paper_audit.critical_cone_epsilon2;
    end
catch exception
    row.error_id=exception.identifier; row.message=exception.message;
    fprintf(2,'%s\n',getReport(exception,'extended','hyperlinks','off'));
end
result=struct('job',job,'row',row,'audit',audit,'paper_audit',paper_audit, ...
    'solver_source',which('solve_costar'),'matlab_version',version, ...
    'lsqnonneg_source',which('lsqnonneg'), ...
    'optimization_toolbox',ver('optim'),'initial_Wmat',initial_W);
save(job.output_file,'result','sol','hist','-v7.3');
[folder,name]=fileparts(job.output_file);
writetable(struct2table(row,'AsArray',true),fullfile(folder,[name '.csv']));
fprintf('PAIRED %s %s seed=%d CRLB=%.10g time=%.3fs KKT=%.3g eigT=%.3g joint=%d; %s\n', ...
    job.label,job.case_name,job.seed,row.crlb,row.optimization_s,row.kkt, ...
    row.lambda_min_tangent,row.joint_pass,row.message);
if ~row.executed
    error('PairedBenchmark:JobFailed','%s',row.message);
end
end

function value=value_or(s,name,fallback)
if isfield(s,name); value=s.(name); else; value=fallback; end
end
