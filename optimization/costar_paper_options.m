function o=costar_paper_options(o)
%COSTAR_PAPER_OPTIONS Safeguarded variant with feasible first-order acceleration.
if nargin==0; o=struct(); end
defaults=struct('max_iter',1000,'epsilon_KKT',1e-5,'epsilon_H',1e-5, ...
    'nu0',1e-5,'refinement_factor',0.5,'tau_bar',1e-4, ...
    'sinr_active_tol',1e-4,'power_active_tol',1e-5,'kappa_tau',0.5, ...
    'rank_tol',1e-11,'nnls_tol',1e-13,'inward_tol',1e-9, ...
    'inward_max_sweeps',2000,'threshold_max_iter',80, ...
    'alpha0',1,'eta_F',0.1,'omega_F',0.1,'guard_max_backtracks',100, ...
    'delta0',0.05,'delta_max',0.5,'eta_accept',0.05, ...
    'eta_shrink',0.25,'eta_expand',0.75,'eta_boundary',0.9, ...
    'gamma_shrink',0.5,'gamma_expand',1.8,'minimum_radius',0, ...
    'feas_tol',1e-10,'restoration_fraction',0.05, ...
    'normal_second_order_cap',2000,'restoration_max_iter',8, ...
    'restoration_regularization',1e-12,'normal_inward_margin',1, ...
    'nc_max_backtracks',100,'cg_max_iter',120,'cg_relative_tol',1e-3, ...
    'max_refinements',80,'record_snapshots',true,'verbose',false, ...
    'print_every',25,'seed',2026, ...
    'guard_directional',false,'guard_cached',true,'guard_step0',1, ...
    'guard_direction_margin',1,'shrink_failed_tangent',true, ...
    'restoration_total_radius',true,'first_order_normal_restore',true, ...
    'feasible_accelerator',true,'guard_scaled_inward',false, ...
    'accelerator_norm_cap',true,'fast_retraction',true, ...
    'fast_retraction_iterations',4,'sinr_inward_margin',1e-5, ...
    'guard_initial_scaling',true,'guard_correction_fraction',0.25, ...
    'guard_cache_min_trials',3,'sinr_margin_fraction',0.1, ...
    'ambient_endpoint_probe',false,'endpoint_probe_factor',10);
names=fieldnames(defaults);
for k=1:numel(names)
    if ~isfield(o,names{k}) || isempty(o.(names{k})); o.(names{k})=defaults.(names{k}); end
end
assert(o.epsilon_KKT>0 && o.epsilon_H>0 && o.nu0>0);
assert(o.kappa_tau>0 && o.kappa_tau<1 && o.refinement_factor>0 && o.refinement_factor<1);
assert(0<o.eta_accept && o.eta_accept<o.eta_shrink && o.eta_shrink<o.eta_expand && o.eta_expand<1);
assert(o.restoration_fraction>0 && o.restoration_fraction<1-o.eta_expand);
assert(o.feas_tol>=0 && o.omega_F>0 && o.omega_F<1 && o.eta_F>0 && o.eta_F<1);
assert(o.delta0>0 && o.delta_max>=o.delta0 && o.gamma_shrink>0 && o.gamma_shrink<1 && o.gamma_expand>1);
if isfield(o,'hessian_model') && ~strcmpi(o.hessian_model,'exact_lagrangian')
    error('COSTAR:PaperOptions','Paper-aligned COSTAR requires the exact Lagrangian HVP.');
end
if isfield(o,'enable_tcg_negative_curvature') && ~o.enable_tcg_negative_curvature
    error('COSTAR:PaperOptions','Paper-aligned COSTAR retains the tCG nonpositive-curvature branch.');
end
end
